# F30k (HPP-721): writes refs_f30k.py - the report links <commit>:<path>:<line> with their whole-line anchor and +1 line,
# read from git at the time of writing; code_f30k.py then re-checks them (and two negative controls).  The lines were
# chosen by hand in the report; this script only freezes their text.  Usage: python mk_refs_f30k.py <MAIN> <out.py>
import subprocess, sys

G = 'C:/Program Files/Git/cmd/git.exe'
MAIN = sys.argv[1]
T = 'a1d1d863'
H = 'src/graphics/host_gpu/'
RD = H + 'renderer/renderDraw.cpp'
LINKS = [
    (T, RD, [2142, 2148, 2196, 2205, 2256, 2277, 2278, 2291, 2312, 3493, 3501, 3637, 3690, 3694]),
    (T, H + 'renderer/image/image.cpp', [204, 217, 237, 270, 278, 283]),
    (T, H + 'vma.cpp', [402, 456]),
    (T, H + 'renderer/cache/textureCache.cpp', [499, 3200, 3394]),
    (T, H + 'renderer/pipeline/descriptors.cpp', [3824]),
    (T, H + 'renderer/image/image.h', [153]),
    (T, H + 'renderer/render.h', [147]),
    (T, H + 'renderer/context.cpp', [325]),
    ('a11007d7', 'docs/track-f/f30h.md', [146]),
]
extra = [a for a in sys.argv[3:]]  # "<path>:<line>" on MAIN
for a in extra:
    p, n = a.rsplit(':', 1)
    LINKS.append((MAIN, p, [int(n)]))
out = ['# generated by mk_refs_f30k.py - (commit, path, line, anchor, +1 line)', 'REFS = [']
for c, p, ns in LINKS:
    s = subprocess.run([G, '-C', 'C:/kyty/KytyPS5', 'show', '%s:%s' % (c, p)], capture_output=True, check=True).stdout.decode('utf-8').split('\n')
    for n in ns:
        a, a1 = s[n - 1].strip(), s[n].strip()
        out.append('    (%r, %r, %d, %r, %r),' % (c, p, n, a, a1))
        print('%s:%s:%d | %s | +1 %s' % (c, p, n, a[:100], a1[:60]))
out.append(']')
open(sys.argv[2], 'wb').write(('\n'.join(out) + '\n').encode('utf-8'))
