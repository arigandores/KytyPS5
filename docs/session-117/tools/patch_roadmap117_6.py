"""ROADMAP: session 117 item 6 (batching and overlap of the waits; the user's question), written before acting."""
from pathlib import Path

P = Path('C:/kyty/KytyPS5/docs/ROADMAP.md')
raw = P.read_bytes().decode('utf-8')
crlf = '\r\n' in raw
s = raw.replace('\r\n', '\n')
ANCHOR = """   часть. Правила вердикта и следствия п. 4 — без изменений.
"""
NEW = ANCHOR + """6. **Пакетирование и перекрытие ожиданий (вопрос пользователя «мб стоит сразу несколько патчей писать и тестить их сразу,
   и только тогда тесты запускать?»; записано до действий).** Замер п. 1 идёт: полный прогон v4.1 `--no-memo` на `ttl114b`
   ≈ 57 мин (итог — п. 7); столько стоит мутационная проверка БОЛЬШОГО ABBA-скорера, наблюдательные скореры меньше.
   **Правила с этого пункта:** (1) **инструменты ТОЛЬКО ИЗМЕРЕНИЯ пакетируются**: всё, что готово к сессии, — в одну
   сборку, один запечатанный прогон, один скорер и один мутационный прогон (например, часть 2 этапа 4 — K3/K4 — идёт
   одной сборкой с тем, что будет готово рядом, а не отдельной сессией на каждый счётчик); (2) **смены умолчаний
   (SHIP) не пакетируются в одно плечо**: у каждой — своя ABBA-пара, иначе выигрыш не приписать; но 2–3 кандидата
   готовятся вместе и их цепочки идут подряд одним заходом; (3) **перекрытие:** мутационный прогон, сборка и написание
   кода идут одновременно — эксклюзивен только запечатанный прогон игры (и замеры времени самих инструментов, как п. 1);
   правило «два тяжёлых задания не одновременно» уточняется: оно о запечатанных прогонах и замерах, не о мутантах рядом
   со сборкой; (4) **объём мутантов по риску:** наблюдательный скорер (вердикт ADMITTED/отчёт, без SHIP) — мутанты на
   допуск и на ветви вердикта; полный объём — для скореров, решающих отгрузку.
"""
assert s.count(ANCHOR) == 1
s = s.replace(ANCHOR, NEW)
if crlf:
    s = s.replace('\n', '\r\n')
P.write_bytes(s.encode('utf-8'))
print('patched', P)
