def gen(name):
    t = rb(os.path.join(SRC, name)).decode('ascii')
    # the old tag binary (FS14 013e1974) becomes the new tag binary FS15; the old installed one (FS13 abab2196) becomes FS14 013e1974
    t = t.replace(TB14, '@NEWTB@').replace(FS13, '@NEWINST@').replace('013e1974', '@NEWTB8@').replace('abab2196', '@NEWINST8@')
    for a, z in STEPS[4:]:
        t = t.replace(a, z)
    t = t.replace('@NEWTB@', TB15).replace('@NEWINST@', TB14).replace('@NEWTB8@', 'bfac84be').replace('@NEWINST8@', '013e1974')
    return t


def head_swap(text, new_head):
    lines = text.split('\n')
    assert lines[0] == '#!/bin/bash'
    i = 1
    while lines[i].startswith('#'):
        i += 1
    return '\n'.join([lines[0]] + new_head.rstrip('\n').split('\n') + lines[i:])


