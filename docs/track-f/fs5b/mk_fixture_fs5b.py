# FS5b (HPP-510, Red Team): port of my FS4b mk_fixture_fs4b.py by mk_fx_scripts_fs5b.py (FixF10Enabled, 0e72bc19 vs 8a56dc2a). Was:
# FS4b (HPP-471, Red Team): fixture of the KYTY_FIX_F10 default parsing on the REAL code. Extracts, from the given git
# commits, the body of the initializer lambda of FixF10Enabled() in pipelineCache.cpp (the lines between
# "static const bool enabled = [] {" and "}();" - for 8a56dc2a the single-expression static) and writes one C++ file per
# commit that #includes the real src/common/envFlag.h of my worktree (= 0e72bc19, envFlag.h untouched by the diff) and
#   mode "env": runs the extracted body against std::getenv("KYTY_FIX_F10") and prints "getenv=<null|str:...> on=<0|1>";
#   mode "arg": runs the same body with value = argv[2] (covers "" without relying on the CRT environment).
# LF out. Usage: python mk_fixture_fs4b.py   (writes fx_0e72bc19.cpp, fx_8a56dc2a.cpp)
import pathlib, subprocess
G = "C:/Program Files/Git/cmd/git.exe"
D = pathlib.Path("C:/kyty/f287/fs5/fs5b")
P = "src/graphics/shader/recompiler/frontend/decode/ShaderDecoder.cpp"


def body(commit):
    src = subprocess.run([G, "-C", "C:/kyty/KytyPS5", "show", commit + ":" + P], capture_output=True, check=True).stdout
    lines = src.decode("utf-8").replace("\r", "").split("\n")
    i = [k for k, l in enumerate(lines) if l.strip() == "bool FixF10Enabled() {"]
    assert len(i) == 1, (commit, i)
    k = i[0]
    end = k + [j for j, l in enumerate(lines[k:]) if l == "}"][0]
    fn = lines[k:end + 1]
    lam = [j for j, l in enumerate(fn) if l.strip() == "static const bool enabled = [] {"]
    if lam:
        a = lam[0]
        b = a + [j for j, l in enumerate(fn[a:]) if l.strip() == "}();"][0]
        inner = fn[a + 1:b]
        # inner: 'const char* value = std::getenv("KYTY_FIX_F10");' then 'return <expr>;'
        assert inner[0].strip() == "const char* value = std::getenv(\"KYTY_FIX_F10\");", inner
        assert len(inner) == 2 and inner[1].strip().startswith("return "), inner
        expr = inner[1].strip()[len("return "):-1]
    else:
        st = [l.strip() for l in fn if l.strip().startswith("static const bool enabled =")]
        assert len(st) == 1, fn
        s = st[0][len("static const bool enabled ="):].strip().rstrip(";")
        # Common::EnvValueOn(std::getenv("KYTY_FIX_F10")) -> the same expression over value
        assert s == "Common::EnvValueOn(std::getenv(\"KYTY_FIX_F10\"))", s
        expr = "Common::EnvValueOn(value)"
    return fn, expr


for c in ("0e72bc19", "8a56dc2a"):
    fn, expr = body(c)
    cpp = "\n".join([
        "// FS4b fixture generated by mk_fixture_fs4b.py from " + c + ":" + P + " FixF10Enabled():",
    ] + ["//   " + l for l in fn] + [
        "#include <cstdio>",
        "#include <cstdlib>",
        "#include <cstring>",
        "#include \"common/envFlag.h\"",
        "static bool Parse(const char* value) { return " + expr + "; }",
        "int main(int argc, char** argv) {",
        "\tif (argc >= 2 && std::strcmp(argv[1], \"env\") == 0) {",
        "\t\tconst char* value = std::getenv(\"KYTY_FIX_F10\");",
        "\t\tif (value == nullptr) { std::printf(\"getenv=null on=%d\\n\", Parse(value) ? 1 : 0); }",
        "\t\telse { std::printf(\"getenv=str:[%s] on=%d\\n\", value, Parse(value) ? 1 : 0); }",
        "\t\treturn 0;",
        "\t}",
        "\tif (argc >= 3 && std::strcmp(argv[1], \"arg\") == 0) {",
        "\t\tstd::printf(\"arg=[%s] on=%d\\n\", argv[2], Parse(argv[2]) ? 1 : 0);",
        "\t\treturn 0;",
        "\t}",
        "\treturn 2;",
        "}",
        "",
    ])
    (D / ("fx_" + c + ".cpp")).write_bytes(cpp.encode("utf-8"))
    print(c, "expr:", expr)
print("OK")
